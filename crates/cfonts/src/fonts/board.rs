#[cfg(test)]
mod tests {
	use std::iter;

	use crate::SUPPORTED_CHARS;

	#[test]
	fn line_pieces_never_hide_in_the_base_color() {
		// a lone ═ in the base color is almost always a line piece missing its
		// <c3>: box frames always carry a corner in the same segment
		let font = &super::FONT_BOARD;
		let glyphs = SUPPORTED_CHARS
			.iter()
			.map(|character| (format!("{character:?}"), font.get_glyph(*character).unwrap()))
			.chain(iter::once((String::from("letter_space"), font.letter_space())));

		for (name, glyph) in glyphs {
			for line in 0..glyph.rows {
				for (text, slot) in glyph.row(line).segments() {
					if slot == Some(0) && text.contains('═') {
						assert!(
							text.chars().any(|character| matches!(character, '╒' | '╕' | '╘' | '╛')),
							"glyph {name} (line {line}) paints \u{2550} with <c1> but no frame corner sits beside it; a lone line is <c3>",
						);
					}
				}
			}
		}
	}
}
